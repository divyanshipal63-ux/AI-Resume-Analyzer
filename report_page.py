
import streamlit as st
from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
)


def make_pdf_report(report):
    """Create a downloadable PDF from the saved analysis results."""
    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=0.65 * inch,
        leftMargin=0.65 * inch,
        topMargin=0.65 * inch,
        bottomMargin=0.65 * inch,
    )

    red = colors.HexColor("#B91C1C")
    light_red = colors.HexColor("#FFF0F0")
    dark = colors.HexColor("#333333")
    grey = colors.HexColor("#666666")

    styles = getSampleStyleSheet()

    styles.add(ParagraphStyle(
        name="ReportTitle",
        parent=styles["Title"],
        textColor=red,
        fontSize=23,
        leading=29,
        alignment=TA_CENTER,
        spaceAfter=8,
    ))

    styles.add(ParagraphStyle(
        name="ReportSubtitle",
        parent=styles["Normal"],
        textColor=grey,
        fontSize=10,
        alignment=TA_CENTER,
        spaceAfter=18,
    ))

    styles.add(ParagraphStyle(
        name="SectionHeading",
        parent=styles["Heading2"],
        textColor=red,
        fontSize=14,
        leading=18,
        spaceBefore=13,
        spaceAfter=7,
    ))

    styles.add(ParagraphStyle(
        name="ReportBody",
        parent=styles["BodyText"],
        textColor=dark,
        fontSize=9.5,
        leading=14,
        spaceAfter=5,
        wordWrap="CJK",
    ))

    def safe_text(value):
        """Escape special HTML characters for PDF paragraphs."""
        if value is None:
            return "Not available"

        if isinstance(value, (list, tuple, set)):
            value = ", ".join(str(item) for item in value)

        if isinstance(value, dict):
            value = "; ".join(
                f"{key}: {val}" for key, val in value.items()
            )

        text = str(value).strip()
        if not text:
            return "Not available"

        return (
            text.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\n", "<br/>")
        )

    story = []

    story.append(Paragraph("AI Resume Analyzer", styles["ReportTitle"]))
    story.append(Paragraph(
        "Detailed Resume Analysis Report",
        styles["ReportSubtitle"],
    ))
    story.append(HRFlowable(
        width="100%",
        thickness=1.5,
        color=red,
        spaceAfter=15,
    ))

    ats_score = report.get("ats_score", "N/A")
    match_score = report.get("match_score", "N/A")

    score_data = [
        [
            Paragraph("<b>ATS Score</b>", styles["ReportBody"]),
            Paragraph("<b>Job Match Score</b>", styles["ReportBody"]),
        ],
        [
            Paragraph(
                f"<font color='#B91C1C' size='20'>"
                f"{safe_text(ats_score)}"
                f"{'%' if ats_score != 'N/A' else ''}</font>",
                styles["ReportBody"],
            ),
            Paragraph(
                f"<font color='#B91C1C' size='20'>"
                f"{safe_text(match_score)}"
                f"{'%' if match_score != 'N/A' else ''}</font>",
                styles["ReportBody"],
            ),
        ],
    ]

    score_table = Table(score_data, colWidths=[3.25 * inch, 3.25 * inch])
    score_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), light_red),
        ("BOX", (0, 0), (-1, -1), 0.8, colors.HexColor("#F1CACA")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.white),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
    ]))

    story.append(score_table)

    def add_section(title, content):
        story.append(Paragraph(title, styles["SectionHeading"]))
        story.append(Paragraph(safe_text(content), styles["ReportBody"]))

    add_section("1. Resume Overview", report.get("summary"))
    add_section("2. Skills Found", report.get("found_skills"))
    add_section("3. Missing Skills", report.get("missing_skills"))
    add_section("4. Resume Improvement Suggestions", report.get("suggestions"))
    add_section("5. AI Resume Feedback", report.get("ai_analysis"))

    story.append(Spacer(1, 15))
    story.append(HRFlowable(
        width="100%",
        thickness=0.7,
        color=colors.HexColor("#F1CACA"),
    ))
    story.append(Spacer(1, 8))
    story.append(Paragraph(
        "Generated by AI Resume Analyzer. Review all suggestions "
        "before updating your resume.",
        styles["ReportSubtitle"],
    ))

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()


def show_report_page():
    """Display Page 5 and allow the user to download a PDF report."""

    st.markdown("""
    <style>
    .report-header {
        background: linear-gradient(135deg, #FFE5E5, #FFFFFF);
        padding: 26px;
        border: 1px solid #F1CACA;
        border-radius: 16px;
        margin-bottom: 22px;
    }

    .report-header h1 {
        color: #B91C1C;
        margin-bottom: 8px;
    }

    .report-header p {
        color: #6B3A3A;
        margin-bottom: 0;
    }

    .report-card {
        background: #FFFFFF;
        border: 1px solid #F1D0D0;
        border-radius: 12px;
        padding: 18px;
        margin-bottom: 12px;
    }

    .report-card h3 {
        color: #B91C1C;
        margin-top: 0;
    }
    </style>
    """, unsafe_allow_html=True)

    if st.button("← Back to Resume Analyzer"):
        st.session_state["page"] = "analyzer"
        st.rerun()

    st.markdown("""
    <div class="report-header">
        <h1>📑 Detailed Resume Report</h1>
        <p>
            Review your resume scores, skills, and personalized
            improvement recommendations.
        </p>
    </div>
    """, unsafe_allow_html=True)

    report = st.session_state.get("resume_report")

    if not report:
        st.warning(
            "No analysis report is available yet. "
            "Please analyze your resume on Page 4 first."
        )

        if st.button("Go to Resume Analyzer", type="primary"):
            st.session_state["page"] = "analyzer"
            st.rerun()

        return

    col1, col2 = st.columns(2)

    with col1:
        st.metric(
            "ATS Score",
            f"{report.get('ats_score', 'N/A')}"
            + ("%" if report.get("ats_score") is not None else ""),
        )

    with col2:
        st.metric(
            "Job Match Score",
            f"{report.get('match_score', 'N/A')}"
            + ("%" if report.get("match_score") is not None else ""),
        )

    st.markdown("### 📝 Resume Overview")
    st.write(report.get("summary") or "No summary available.")

    col3, col4 = st.columns(2)

    with col3:
        st.markdown(
            '<div class="report-card"><h3>✅ Skills Found</h3></div>',
            unsafe_allow_html=True,
        )
        found_skills = report.get("found_skills", [])
        if found_skills:
            for skill in found_skills:
                st.write(f"✓ {skill}")
        else:
            st.write("No matching skills found.")

    with col4:
        st.markdown(
            '<div class="report-card"><h3>📌 Missing Skills</h3></div>',
            unsafe_allow_html=True,
        )
        missing_skills = report.get("missing_skills", [])
        if missing_skills:
            for skill in missing_skills:
                st.write(f"• {skill}")
        else:
            st.write("No missing skills recorded.")

    st.markdown("### 💡 Improvement Suggestions")
    suggestions = report.get("suggestions", [])
    if isinstance(suggestions, (list, tuple)):
        for suggestion in suggestions:
            st.write(f"• {suggestion}")
    else:
        st.write(suggestions or "No suggestions available.")

    st.markdown("### 🤖 AI Resume Feedback")
    ai_analysis = report.get("ai_analysis")

    if isinstance(ai_analysis, dict):
        for key, value in ai_analysis.items():
            st.markdown(f"**{key.replace('_', ' ').title()}**")
            st.write(value)
    else:
        st.write(ai_analysis or "No AI feedback available.")

    pdf_data = make_pdf_report(report)

    st.download_button(
        label="📥 Download Detailed Report (PDF)",
        data=pdf_data,
        file_name="AI_Resume_Analysis_Report.pdf",
        mime="application/pdf",
        use_container_width=True,
        type="primary",
    )
